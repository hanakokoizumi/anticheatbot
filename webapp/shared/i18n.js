  function adminT(lc, k) {
    lc = normalizeLocale(lc);
    return (
      pick(ADMIN[lc], k) ||
      pick(ADMIN.en, k) ||
      pick(ADMIN['zh-Hans'], k) ||
      k
    );
  }

  function formatStr(s, vars) {
    if (!vars) return s;
    return String(s).replace(/\{(\w+)\}/g, function (_, name) {
      return vars[name] != null ? String(vars[name]) : '';
    });
  }

  function verifyT(lc, k, vars) {
    lc = normalizeLocale(lc);
    var s =
      pick(VERIFY[lc], k) ??
      pick(VERIFY.en, k) ??
      pick(VERIFY['zh-Hans'], k) ??
      k;
    var v = vars;
    if (k === 'quizFailClosing') {
      v = Object.assign({ seconds: 5 }, vars && typeof vars === 'object' ? vars : {});
    }
    return formatStr(s, v);
  }

  function applyAdminLocale(root, lc) {
    lc = normalizeLocale(lc);
    var el = root || document;
    el.querySelectorAll('[data-i18n]').forEach(function (node) {
      var k = node.getAttribute('data-i18n');
      if (!k) return;
      node.textContent = adminT(lc, k);
    });
    el.querySelectorAll('[data-i18n-placeholder]').forEach(function (node) {
      var k = node.getAttribute('data-i18n-placeholder');
      if (!k) return;
      node.placeholder = adminT(lc, k);
    });
    el.querySelectorAll('[data-i18n-aria]').forEach(function (node) {
      var k = node.getAttribute('data-i18n-aria');
      if (!k) return;
      var s = adminT(lc, k);
      node.setAttribute('aria-label', s);
      node.setAttribute('title', s);
    });
    if (typeof document !== 'undefined') {
      var titleNode = document.querySelector('title');
      if (titleNode && !titleNode.hasAttribute('data-skip-admin-doc-title')) {
        titleNode.textContent = adminT(lc, 'docTitle');
      }
    }
  }

  function adminFormat(lc, k, vars) {
    return formatStr(adminT(lc, k), vars);
  }

